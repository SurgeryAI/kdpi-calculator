#!/usr/bin/env python3
"""Generate pinned Swift KDPI mapping data from the reviewed JSON catalog."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from kdpi_mapping_tools import validate_catalog


def identifier(index: int, table: dict[str, object]) -> str:
    return f"release{index}_{str(table['releaseLabel']).lower().replace(' ', '_').replace('.', '').replace('-', '_')}"


def render_table(index: int, table: dict[str, object]) -> str:
    bounds = table["upperBounds"]
    lines = []
    for start in range(0, len(bounds), 6):
        chunk = ", ".join(f"{float(value):.14f}" for value in bounds[start:start + 6])
        lines.append(f"            {chunk},")
    formula = "legacyRaceHCV" if table["formulaVersion"] == "legacyRaceHCV" else "raceHCVNeutral2024"
    return "\n".join((
        f"    private static let {identifier(index, table)} = KDPIMappingTable(",
        f"        referenceYear: {table['referenceYear']},",
        f"        releaseLabel: \"{table['releaseLabel']}\",",
        f"        releaseYear: {table['releaseYear']},",
        f"        timelinePosition: {float(table['timelinePosition']):.2f},",
        f"        databaseAsOf: \"{table['databaseAsOf']}\",",
        f"        formulaVersion: .{formula},",
        f"        scalingFactor: {float(table['scalingFactor']):.14f},",
        f"        diabetesPrevalence: {float(table['diabetesPrevalence']):.14f},",
        f"        hypertensionPrevalence: {float(table['hypertensionPrevalence']):.14f},",
        f"        sourceURL: \"{table['sourceURL']}\",",
        "        upperBounds: [",
        *lines,
        "        ]",
        "    )",
    ))


def render_swift(catalog_path: Path) -> str:
    raw = json.loads(catalog_path.read_text(encoding="utf-8"))
    if raw.get("schemaVersion") != 1:
        raise ValueError("Unsupported catalog schema")
    tables = validate_catalog(raw["tables"])
    rendered = [render_table(index, table) for index, table in enumerate(tables)]
    names = [identifier(index, table) for index, table in enumerate(tables)]
    return "\n".join((
        "// Generated by Scripts/generate_kdpi_mapping_data.py.",
        "// Source: Research/kdpi_mapping_tables.json. Do not hand-edit thresholds.",
        "",
        "import Foundation",
        "",
        "enum KDRIFormulaVersion: String, Sendable {",
        "    case legacyRaceHCV",
        "    case raceHCVNeutral2024",
        "",
        "    var shortLabel: String {",
        "        switch self {",
        "        case .legacyRaceHCV: return \"Original formula\"",
        "        case .raceHCVNeutral2024: return \"2024 refit\"",
        "        }",
        "    }",
        "}",
        "",
        "struct KDPIMappingTable: Identifiable, Sendable {",
        "    let referenceYear: Int",
        "    let releaseLabel: String",
        "    let releaseYear: Int",
        "    let timelinePosition: Double",
        "    let databaseAsOf: String",
        "    let formulaVersion: KDRIFormulaVersion",
        "    let scalingFactor: Double",
        "    let diabetesPrevalence: Double",
        "    let hypertensionPrevalence: Double",
        "    let sourceURL: String",
        "    let upperBounds: [Double]",
        "",
        "    var id: String { releaseLabel }",
        "",
        "    func percentile(for scaledKDRI: Double) -> Int {",
        "        guard scaledKDRI.isFinite else { return 100 }",
        "        var low = 0",
        "        var high = upperBounds.count",
        "        while low < high {",
        "            let middle = low + (high - low) / 2",
        "            if scaledKDRI <= upperBounds[middle] { high = middle }",
        "            else { low = middle + 1 }",
        "        }",
        "        return min(low, 100)",
        "    }",
        "}",
        "",
        "enum KDPIMappingTables {",
        *rendered,
        "",
        f"    static let current = {names[-1]}",
        "",
        "    // Historical data is initialized only when Time Machine is opened.",
        "    static let all: [KDPIMappingTable] = [",
        *(f"        {name}," for name in names),
        "    ]",
        "}",
        "",
    ))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalog", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render_swift(args.catalog)
    if args.check:
        existing = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if existing != output:
            raise SystemExit(f"{args.output} is stale")
        print(f"{args.output} is current")
        return
    args.output.write_text(output, encoding="utf-8")
    print(f"Generated {args.output}")


if __name__ == "__main__":
    main()
